CREATE TABLE public.admin (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    username character varying(255),
    password character varying(255),
    name character varying(255),
    role character varying(255),
    avatar character varying(255),
    password_version integer DEFAULT 1 NOT NULL,
    CONSTRAINT id PRIMARY KEY (id)
);

CREATE TABLE public.category (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(50) NOT NULL,
    description character varying(200),
    sort_order integer DEFAULT 0 NOT NULL,
    status character varying(20) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT category_pkey PRIMARY KEY (id),
    CONSTRAINT chk_category_status CHECK (
        status::text = ANY (ARRAY['visible'::character varying::text, 'hidden'::character varying::text])
    ),
    CONSTRAINT uk_category_name UNIQUE (name)
);

CREATE TABLE public.tag (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(50) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT tag_pkey PRIMARY KEY (id),
    CONSTRAINT uk_tag_name UNIQUE (name)
);

CREATE TABLE public.article (
    id bigint GENERATED ALWAYS AS IDENTITY,
    category_id bigint,
    title character varying(120) NOT NULL,
    summary character varying(300),
    content text NOT NULL,
    cover_url character varying(500),
    status character varying(20) NOT NULL,
    is_top boolean DEFAULT false NOT NULL,
    is_recommend boolean DEFAULT false NOT NULL,
    view_count integer DEFAULT 0 NOT NULL,
    comment_count integer DEFAULT 0 NOT NULL,
    published_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    like_count integer DEFAULT 0 NOT NULL,
    CONSTRAINT article_pkey PRIMARY KEY (id),
    CONSTRAINT fk_article_category FOREIGN KEY (category_id)
        REFERENCES public.category(id) ON DELETE RESTRICT
);

ALTER TABLE public.article
    ADD CONSTRAINT article_status_check
    CHECK (
        status::text = ANY (
            ARRAY[
                'draft'::character varying::text,
                'published'::character varying::text,
