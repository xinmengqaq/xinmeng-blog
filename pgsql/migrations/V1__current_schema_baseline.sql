CREATE TABLE public.article_like (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    article_id bigint NOT NULL,
    visitor_key_hash character(64) NOT NULL,
    ip_hash character(64) NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT article_like_pkey PRIMARY KEY (id),
    CONSTRAINT article_like_article_id_fkey FOREIGN KEY (article_id)
        REFERENCES public.article(id) ON DELETE CASCADE
);

CREATE TABLE public.article_tag (
    article_id bigint NOT NULL,
    tag_id bigint NOT NULL,
    CONSTRAINT uk_article_tag_article_id_tag_id UNIQUE (article_id, tag_id),
    CONSTRAINT fk_article_tag_article FOREIGN KEY (article_id)
        REFERENCES public.article(id) ON DELETE CASCADE,
    CONSTRAINT fk_article_tag_tag FOREIGN KEY (tag_id)
        REFERENCES public.tag(id) ON DELETE CASCADE
);

CREATE TABLE public.blog_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email character varying(320) NOT NULL,
    password character varying(255) NOT NULL,
    nickname character varying(50) NOT NULL,
    avatar character varying(500),
    status character varying(20) DEFAULT 'enabled'::character varying NOT NULL,
    password_version integer DEFAULT 1 NOT NULL,
    delete_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version integer DEFAULT 1 NOT NULL,
    CONSTRAINT blog_user_pkey PRIMARY KEY (id),
    CONSTRAINT uk_blog_user_email UNIQUE (email),
    CONSTRAINT ck_blog_user_status CHECK (
        status::text = ANY (
            ARRAY[
                'enabled'::character varying::text,
                'disabled'::character varying::text,
                'pending_deletion'::character varying::text
            ]
        )
    ),
    CONSTRAINT ck_blog_user_delete_at CHECK (
        status::text = 'pending_deletion'::text AND delete_at IS NOT NULL
        OR status::text = ANY (
            ARRAY['enabled'::character varying::text, 'disabled'::character varying::text]
        ) AND delete_at IS NULL
    )
);

CREATE SEQUENCE public.music_id_seq AS bigint;

CREATE TABLE public.music (
    id bigint DEFAULT nextval('public.music_id_seq'::regclass) NOT NULL,
    title character varying(120) NOT NULL,
    artist character varying(120),
    audio_url character varying(500) NOT NULL,
    duration_ms integer NOT NULL,
    is_enabled boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT pk_music PRIMARY KEY (id),
    CONSTRAINT uq_music_audio_url UNIQUE (audio_url),
    CONSTRAINT ck_music_duration_positive CHECK (duration_ms > 0)
);

ALTER SEQUENCE public.music_id_seq OWNED BY public.music.id;

